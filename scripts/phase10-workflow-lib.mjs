import {
  createHash,
} from "node:crypto";
import {
  existsSync,
  readFileSync,
} from "node:fs";
import {
  dirname,
  resolve,
} from "node:path";
import {
  fileURLToPath,
} from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_ROOT = resolve(SCRIPT_DIR, "..");
export const WORKFLOW_PATH = "docs/phase10-workflow/workflow.json";

export function readJson(root, relativePath) {
  return JSON.parse(readFileSync(resolve(root, relativePath), "utf8"));
}

export function readText(root, relativePath) {
  return readFileSync(resolve(root, relativePath), "utf8");
}

export function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

export function parseSectionNumber(section) {
  const match = /^§(\d+)$/.exec(section ?? "");
  return match ? Number(match[1]) : null;
}

export function sectionLabel(sectionNumber) {
  return `§${sectionNumber}`;
}

export function extractRoadmapSections(roadmap) {
  return [...roadmap.matchAll(/^## §(\d+)\.\s+(.+)$/gm)].map((match) => ({
    number: Number(match[1]),
    title: match[2].trim(),
  }));
}

export function currentSectionTitle(workflow, state, roadmap) {
  const number = parseSectionNumber(state.current_section);
  const record = extractRoadmapSections(roadmap).find(
    (section) => section.number === number,
  );
  return record?.title ?? state.section?.title ?? "Unknown section";
}

function displayList(items, empty = "None recorded.") {
  if (!items?.length) return empty;
  return items.map((item) => `- \`${item}\``).join("\n");
}

function activeReadingPaths(workflow, state) {
  const paths = [];
  if (state.section?.spec_doc) paths.push(state.section.spec_doc);
  for (const path of state.section?.direction_docs ?? []) paths.push(path);
  if (state.section?.visual_reference_dir) {
    paths.push(state.section.visual_reference_dir);
  }
  if (state.section?.handoff) paths.push(state.section.handoff);
  return paths;
}

export function renderActiveContext(root = DEFAULT_ROOT) {
  const workflowText = readText(root, WORKFLOW_PATH);
  const workflow = JSON.parse(workflowText);
  const stateText = readText(root, workflow.files.state);
  const state = JSON.parse(stateText);
  const roadmapText = readText(root, workflow.files.roadmap);
  const title = currentSectionTitle(workflow, state, roadmapText);
  const sectionNumber = parseSectionNumber(state.current_section);
  const terminal = workflow.managed_sections.terminal;
  const stage = workflow.stages[state.stage];
  const readingPaths = activeReadingPaths(workflow, state);
  const gates = workflow.global_gates
    .map((gate) => `- **${gate.id}:** ${gate.rule}`)
    .join("\n");
  const transitions = Object.entries(workflow.transitions)
    .map(([event, result]) => `- \`${event}\` → \`${result}\``)
    .join("\n");
  const sourceHashes = [
    [WORKFLOW_PATH, workflowText],
    [workflow.files.state, stateText],
    [workflow.files.roadmap, roadmapText],
    ...(workflow.context.active_context_hash_sources ?? []).map((path) => [
      path,
      readText(root, path),
    ]),
  ]
    .map(([path, contents]) => `- \`${path}\`: \`${sha256(contents)}\``)
    .join("\n");

  return `<!-- GENERATED by scripts/phase10-generate-context.mjs. DO NOT EDIT. -->
# Phase 10 Active Context

This is the compact routing and safety packet for the next Phase 10 turn. It is
generated from the canonical workflow manifest, live state, and roadmap. Read
the deeper historical documents only when this packet or the current task names
them.

## Live route

- Phase: ${workflow.phase}
- Current section: **${state.current_section} — ${title}**
- Managed range: §${workflow.managed_sections.first}–§${terminal}
- Stage: \`${state.stage}\`
- Role: \`${state.role}\`
- Status: \`${state.status}\`
- Next actor: \`${state.next_actor}\`
- Expected actor for this stage: \`${stage?.next_actor ?? "INVALID"}\`
- Stop reason: ${state.stop_reason ?? "none"}

The current state is ${sectionNumber === terminal ? "at" : "before"} the
terminal section. Never infer the terminal section from prose; read
\`workflow.managed_sections.terminal\` from
\`${WORKFLOW_PATH}\`.

## Required reading for this turn

Always read:

${displayList(workflow.context.always_read)}

Then read the current, specifically routed sources:

${displayList(readingPaths)}

Historical sources are available on demand and are not recurring prompt
payload:

${displayList(workflow.context.history_on_demand)}

## Current section conditions

${state.section?.note ?? "No section-specific note is recorded."}

Open bounded findings:

${
  state.section?.findings?.length
    ? state.section.findings.map((finding) => `- ${JSON.stringify(finding)}`).join("\n")
    : "None."
}

Acceptance ledger:

- ${
  state.section?.acceptance_ledger
    ? `\`${state.section.acceptance_ledger}\``
    : state.stage === "specify"
      ? "Created by the lead with the section specification."
      : "Not recorded."
}

## Global gates

${gates}

## State transitions

${transitions}

A normal passing review accepts the verified candidate and initializes the next
section in the same Claude Lead turn. The legacy \`accept\` stage remains
supported only for already-routed state or explicit owner-exception handling.

## Verification contract

${workflow.verification.policy}

- Implementation candidate: ${workflow.verification.implementation_candidate
    .map((command) => `\`${command}\``)
    .join(", ")}
- Independent final review: ${workflow.verification.independent_final_review
    .map((command) => `\`${command}\``)
    .join(", ")}
- Documentation-only acceptance rerun: none

## Source hashes

These hashes make stale generated context mechanically detectable:

${sourceHashes}
`;
}

export function expandDriftTemplate(template, workflow) {
  return template.replaceAll(
    "{terminal}",
    String(workflow.managed_sections.terminal),
  );
}

export function validateAcceptanceLedger(workflow, ledger, options = {}) {
  const errors = [];
  const add = (condition, message) => {
    if (!condition) errors.push(message);
  };
  const ledgerConfig = workflow.acceptance_ledger;
  const sectionNumber = parseSectionNumber(ledger.section);

  add(
    ledger.schema_version === ledgerConfig.schema_version,
    `acceptance ledger schema_version must be ${ledgerConfig.schema_version}`,
  );
  add(ledger.phase === workflow.phase, `acceptance ledger phase must be ${workflow.phase}`);
  add(
    Number.isInteger(sectionNumber) &&
      sectionNumber >= workflow.managed_sections.first &&
      sectionNumber <= workflow.managed_sections.terminal,
    `acceptance ledger section "${ledger.section}" is outside the managed range`,
  );
  add(typeof ledger.spec_doc === "string" && ledger.spec_doc.length > 0, "acceptance ledger spec_doc is required");
  if (Number.isInteger(sectionNumber)) {
    const expectedSpecPath = ledgerConfig.spec_path_pattern.replace(
      "{N}",
      String(sectionNumber),
    );
    add(
      ledger.spec_doc === expectedSpecPath,
      `acceptance ledger spec_doc must be ${expectedSpecPath}`,
    );
  }
  add(
    ledger.candidate_sha === null || /^[0-9a-f]{40}$/.test(ledger.candidate_sha),
    "acceptance ledger candidate_sha must be null or a 40-character lowercase SHA",
  );
  if (options.requireActor === "reviewer") {
    add(
      /^[0-9a-f]{40}$/.test(ledger.candidate_sha ?? ""),
      "reviewer completion requires the candidate's 40-character lowercase SHA",
    );
  }
  const criteria = Array.isArray(ledger.criteria) ? ledger.criteria : [];
  add(criteria.length > 0, "acceptance ledger criteria must be non-empty");

  const ids = new Set();
  for (const [index, rawCriterion] of criteria.entries()) {
    const criterion =
      rawCriterion && typeof rawCriterion === "object" ? rawCriterion : {};
    const prefix = `criterion ${index + 1}`;
    add(
      criterion === rawCriterion,
      `${prefix} must be an object`,
    );
    add(typeof criterion.id === "string" && /^[A-Z]+-[0-9]{2,3}$/.test(criterion.id), `${prefix} id is invalid`);
    add(!ids.has(criterion.id), `${prefix} id "${criterion.id}" is duplicated`);
    ids.add(criterion.id);
    add(ledgerConfig.dimensions.includes(criterion.dimension), `${prefix} dimension "${criterion.dimension}" is invalid`);
    add(ledgerConfig.risks.includes(criterion.risk), `${prefix} risk "${criterion.risk}" is invalid`);
    add(typeof criterion.description === "string" && criterion.description.length > 0, `${prefix} description is required`);
    add(
      criterion.verifier &&
        ["command", "browser", "visual", "manual"].includes(criterion.verifier.kind),
      `${prefix} verifier.kind is invalid`,
    );
    const requiredArtifacts = Array.isArray(criterion.required_artifacts)
      ? criterion.required_artifacts
      : [];
    add(Array.isArray(criterion.required_artifacts), `${prefix} required_artifacts must be an array`);
    add(
      requiredArtifacts.every(
        (artifact) => typeof artifact === "string" && artifact.length > 0,
      ),
      `${prefix} required_artifacts must contain non-empty paths`,
    );
    if (criterion.verifier?.kind === "command") {
      add(
        typeof criterion.verifier.command === "string" &&
          criterion.verifier.command.length > 0,
        `${prefix} command verifier requires a command`,
      );
    }
    for (const actor of ["implementer", "reviewer"]) {
      const result =
        criterion[actor] && typeof criterion[actor] === "object"
          ? criterion[actor]
          : {};
      const evidence = Array.isArray(result.evidence) ? result.evidence : [];
      add(result && ledgerConfig.statuses.includes(result.status), `${prefix} ${actor}.status is invalid`);
      add(Array.isArray(result?.evidence), `${prefix} ${actor}.evidence must be an array`);
      add(
        evidence.every(
          (artifact) => typeof artifact === "string" && artifact.length > 0,
        ),
        `${prefix} ${actor}.evidence must contain non-empty entries`,
      );
      if (options.requireActor === actor) {
        const allowedCompleteStatuses =
          actor === "implementer"
            ? ["pass", "not_applicable", "deferred_to_reviewer"]
            : ["pass", "not_applicable"];
        add(
          allowedCompleteStatuses.includes(result?.status),
          `${prefix} ${actor}.status must be ${allowedCompleteStatuses.join(", ")}`,
        );
        add(
            result?.status === "not_applicable" ||
            result?.status === "deferred_to_reviewer" ||
            evidence.length > 0,
          `${prefix} ${actor} pass requires retained evidence`,
        );
        if (
          ["not_applicable", "deferred_to_reviewer"].includes(result?.status)
        ) {
          add(
            typeof result?.notes === "string" && result.notes.length > 0,
            `${prefix} ${actor} ${result?.status} requires notes`,
          );
        }
      }
    }
    if (options.requireActor === "reviewer") {
      const implementerEvidence = Array.isArray(
        criterion.implementer?.evidence,
      )
        ? criterion.implementer.evidence
        : [];
      const reviewerEvidence = Array.isArray(criterion.reviewer?.evidence)
        ? criterion.reviewer.evidence
        : [];
      const retainedEvidence = new Set([
        ...implementerEvidence,
        ...reviewerEvidence,
      ]);
      for (const artifact of requiredArtifacts) {
        add(
          retainedEvidence.has(artifact),
          `${prefix} required artifact "${artifact}" is not retained in evidence`,
        );
      }
    }
  }

  return errors;
}

export function validateWorkflowRepository(root = DEFAULT_ROOT) {
  const errors = [];
  const add = (condition, message) => {
    if (!condition) errors.push(message);
  };
  const workflow = readJson(root, WORKFLOW_PATH);
  const state = readJson(root, workflow.files.state);
  const roadmap = readText(root, workflow.files.roadmap);
  const sectionNumber = parseSectionNumber(state.current_section);
  const roadmapSections = extractRoadmapSections(roadmap);
  const roadmapNumbers = roadmapSections.map((section) => section.number);
  const terminal = workflow.managed_sections.terminal;

  add(workflow.schema_version === 1, "workflow schema_version must be 1");
  add(workflow.phase === state.phase, "workflow phase and state phase must match");
  add(
    Number.isInteger(sectionNumber) &&
      sectionNumber >= workflow.managed_sections.first &&
      sectionNumber <= terminal,
    `current_section "${state.current_section}" is outside the managed range`,
  );
  add(
    roadmapNumbers.includes(sectionNumber),
    `roadmap has no heading for ${state.current_section}`,
  );
  add(
    Math.max(...roadmapNumbers) === terminal,
    `roadmap terminal section must be §${terminal}`,
  );
  add(
    roadmap.includes(
      expandDriftTemplate(
        workflow.drift_checks.roadmap_terminal_phrase,
        workflow,
      ),
    ),
    `roadmap final-report marker must name §${terminal}`,
  );
  add(
    state.role === workflow.stages[state.stage]?.role,
    `stage "${state.stage}" requires role "${workflow.stages[state.stage]?.role}"`,
  );
  add(
    state.section?.id === state.current_section,
    `state.section.id "${state.section?.id}" must match current_section`,
  );
  if (state.status === "ready") {
    add(
      state.next_actor === workflow.stages[state.stage]?.next_actor,
      `stage "${state.stage}" requires next_actor "${workflow.stages[state.stage]?.next_actor}"`,
    );
    add(state.stop_reason === null, "ready state requires stop_reason null");
  }
  if (state.status === "blocked") {
    add(state.next_actor === "devan", "blocked state requires next_actor devan");
    add(
      typeof state.stop_reason === "string" && state.stop_reason.length > 0,
      "blocked state requires a non-empty stop_reason",
    );
  }
  if (state.status === "complete") {
    add(sectionNumber === terminal, `complete state requires §${terminal}`);
    add(state.next_actor === "devan", "complete state requires next_actor devan");
  }

  for (const promptPath of workflow.drift_checks.operational_prompts) {
    add(existsSync(resolve(root, promptPath)), `missing operational prompt ${promptPath}`);
    if (existsSync(resolve(root, promptPath))) {
      const prompt = readText(root, promptPath);
      add(
        prompt.includes(workflow.drift_checks.prompt_terminal_token),
        `${promptPath} must derive the terminal section from the workflow manifest`,
      );
    }
  }

  const activePath = resolve(root, workflow.files.active_context);
  add(existsSync(activePath), `missing generated active context ${workflow.files.active_context}`);
  if (existsSync(activePath)) {
    add(
      readFileSync(activePath, "utf8") === renderActiveContext(root),
      `${workflow.files.active_context} is stale; run npm run phase10:context`,
    );
  }

  const ledgerPath = state.section?.acceptance_ledger;
  const ledgerRequired =
    sectionNumber >= workflow.acceptance_ledger.required_from_section &&
    state.stage !== "specify";
  if (state.stage !== "specify") {
    add(
      typeof state.section?.spec_doc === "string" &&
        state.section.spec_doc.length > 0,
      `section ${state.current_section} requires section.spec_doc after specify`,
    );
    if (typeof state.section?.spec_doc === "string") {
      add(
        existsSync(resolve(root, state.section.spec_doc)),
        `section spec ${state.section.spec_doc} does not exist`,
      );
    }
  }
  if (ledgerRequired) {
    add(
      typeof ledgerPath === "string" && ledgerPath.length > 0,
      `section ${state.current_section} requires section.acceptance_ledger after specify`,
    );
  }
  if (ledgerPath) {
    const expectedLedgerPath =
      workflow.acceptance_ledger.path_pattern.replace(
        "{N}",
        String(sectionNumber),
      );
    add(
      ledgerPath === expectedLedgerPath,
      `acceptance ledger path must be ${expectedLedgerPath}`,
    );
    const absoluteLedgerPath = resolve(root, ledgerPath);
    add(existsSync(absoluteLedgerPath), `acceptance ledger ${ledgerPath} does not exist`);
    if (existsSync(absoluteLedgerPath)) {
      const ledger = readJson(root, ledgerPath);
      const requireActor =
        ["review", "remediate"].includes(state.stage)
          ? "implementer"
          : state.stage === "accept"
            ? "reviewer"
            : undefined;
      errors.push(
        ...validateAcceptanceLedger(workflow, ledger, { requireActor }),
      );
      add(
        ledger.section === state.current_section,
        `acceptance ledger section "${ledger.section}" does not match state`,
      );
      add(
        ledger.spec_doc === state.section.spec_doc,
        "acceptance ledger spec_doc does not match state.section.spec_doc",
      );
    }
  }

  const historyIds = new Set();
  const historyRecords = Array.isArray(state.sections_history)
    ? state.sections_history
    : [];
  add(
    Array.isArray(state.sections_history),
    "sections_history must be an array",
  );
  for (const rawRecord of historyRecords) {
    const record =
      rawRecord && typeof rawRecord === "object" ? rawRecord : {};
    add(record === rawRecord, "history records must be objects");
    const historySectionNumber = parseSectionNumber(record.id);
    add(
      Number.isInteger(historySectionNumber),
      `history record id "${record.id}" is invalid`,
    );
    add(!historyIds.has(record.id), `history record "${record.id}" is duplicated`);
    historyIds.add(record.id);
    add(
      record.status === "complete",
      `history record "${record.id}" must have status complete`,
    );
    add(
      /^[0-9a-f]{40}$/.test(record.accepted_commit ?? ""),
      `history record "${record.id}" requires a 40-character accepted_commit`,
    );

    if (
      historySectionNumber >=
      workflow.acceptance_ledger.required_from_section
    ) {
      const expectedHistoryLedgerPath =
        workflow.acceptance_ledger.path_pattern.replace(
          "{N}",
          String(historySectionNumber),
        );
      add(
        record.acceptance_ledger === expectedHistoryLedgerPath,
        `history record "${record.id}" must retain acceptance_ledger ${expectedHistoryLedgerPath}`,
      );
      const hasHistoryLedgerPath =
        typeof record.acceptance_ledger === "string" &&
        record.acceptance_ledger.length > 0;
      const absoluteHistoryLedgerPath = hasHistoryLedgerPath
        ? resolve(root, record.acceptance_ledger)
        : null;
      add(
        absoluteHistoryLedgerPath !== null &&
          existsSync(absoluteHistoryLedgerPath),
        `accepted ledger ${record.acceptance_ledger ?? "(missing)"} does not exist`,
      );
      if (
        absoluteHistoryLedgerPath !== null &&
        existsSync(absoluteHistoryLedgerPath)
      ) {
        const acceptedLedger = readJson(root, record.acceptance_ledger);
        errors.push(
          ...validateAcceptanceLedger(workflow, acceptedLedger, {
            requireActor: "reviewer",
          }).map((error) => `${record.id} accepted ledger: ${error}`),
        );
        add(
          acceptedLedger.section === record.id,
          `${record.id} accepted ledger section does not match history`,
        );
        add(
          typeof acceptedLedger.spec_doc === "string" &&
            existsSync(resolve(root, acceptedLedger.spec_doc)),
          `${record.id} accepted ledger spec ${acceptedLedger.spec_doc} does not exist`,
        );
        add(
          acceptedLedger.candidate_sha === record.accepted_commit,
          `${record.id} accepted ledger candidate_sha must match accepted_commit`,
        );
      }
    }
  }

  return errors;
}
